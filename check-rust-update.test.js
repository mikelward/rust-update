test("verifyUpstream checks additions like changes", async () => {
  const newText = renderLock([
    { name: "app", version: "0.0.0", deps: ["fresh"] },
    reg({ name: "fresh", version: "0.7.2" }),
  ]);
  const { fetcher } = upstream({ fresh: { versions: [{ vers: "0.7.2" }], dates: { "0.7.2": FRESH_DATE } } });
  const errors = await verifyUpstream(
    newText,
    { changes: [], added: [{ name: "fresh", version: "0.7.2", checksum: "c-fresh-0.7.2" }] },
    settings(fetcher),
  );
  assert.equal(errors.length, 1);
  assert.match(errors[0], /fresh 0\.7\.2: published .* inside the 5-day cooldown/);
});
