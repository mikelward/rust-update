test("soundness: unresolvable, ambiguous, and orphaned packages are refused", () => {
  const dangling = parseLockfile(renderLock([{ name: "app", version: "0.0.0", deps: ["ghost"] }]));
  assert.match(soundnessFailures(dangling, "t").join("\n"), /resolves to 0 packages/);
  const ambiguous = parseLockfile(
    renderLock([
      { name: "app", version: "0.0.0", deps: ["syn"] },
      reg({ name: "syn", version: "2.0.119" }),
      reg({ name: "syn", version: "3.0.2" }),
    ]),
  );
  assert.match(soundnessFailures(ambiguous, "t").join("\n"), /resolves to 2 packages/);
  const orphaned = parseLockfile(
    renderLock([{ name: "app", version: "0.0.0" }, reg({ name: "stray", version: "1.0.0" })]),
  );
  assert.match(soundnessFailures(orphaned, "t").join("\n"), /not reachable/);
});

test("an unchanged package gaining a declared-looking edge is collected, not decided", () => {
  const result = validateLockfileUpdate(
    renderLock([
      { name: "app", version: "0.0.0", deps: ["a", "b"] },
      reg({ name: "a", version: "1.2.0" }),
      reg({ name: "b", version: "2.0.0" }),
    ]),
    renderLock([
      { name: "app", version: "0.0.0", deps: ["a", "b"] },
      reg({ name: "a", version: "1.2.5" }),
      // b held still but now records an edge — feature unification, or a graft.
      reg({ name: "b", version: "2.0.0", deps: ["a"] }),
    ]),
  );
  assert.deepEqual(result.errors, []);
  assert.deepEqual(result.depChanged, [{ name: "b", version: "2.0.0", added: ["a"], removed: [] }]);
});

