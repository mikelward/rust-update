test("diffLockfiles pairs compat groups and separates arrivals from departures", () => {
  const before = parseLockfile(
    renderLock([
      reg({ name: "a", version: "1.2.0" }),
      reg({ name: "syn", version: "2.0.119" }),
      reg({ name: "gone", version: "0.3.1" }),
    ]),
  );
  const after = parseLockfile(
    renderLock([
      reg({ name: "a", version: "1.3.0" }),
      reg({ name: "syn", version: "2.0.119" }),
      reg({ name: "syn", version: "3.0.2" }),
      reg({ name: "fresh", version: "0.1.0" }),
    ]),
  );
  const diff = diffLockfiles(before, after);
  assert.deepEqual(diff.errors, []);
  assert.deepEqual(diff.changed.map((c) => `${c.name} ${c.from}->${c.to}`), ["a 1.2.0->1.3.0"]);
  assert.deepEqual(diff.added.map((p) => `${p.name} ${p.version}`).sort(), ["fresh 0.1.0", "syn 3.0.2"]);
  assert.deepEqual(diff.removed.map((p) => `${p.name} ${p.version}`), ["gone 0.3.1"]);
  assert.equal(diff.unchanged.length, 1);
});

test("diffLockfiles refuses two semver-compatible versions of one crate", () => {
  const twice = parseLockfile(
    renderLock([reg({ name: "a", version: "1.2.0" }), reg({ name: "a", version: "1.3.0" })]),
  );
  const diff = diffLockfiles(twice, twice);
  assert.ok(diff.errors.length >= 1);
  assert.match(diff.errors[0], /two semver-compatible versions/);
});

