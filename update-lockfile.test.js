// ---------------------------------------------------------------------------
// The hardened fetcher, against a stubbed global fetch.
// ---------------------------------------------------------------------------

const withFetch = async (impl, run) => {
  const real = globalThis.fetch;
  globalThis.fetch = impl;
  try {
    return await run();
  } finally {
    globalThis.fetch = real;
  }
};

test("httpsFetcher follows https redirects and refuses an http hop", async () => {
  const hops = [];
  await withFetch(
    async (url) => {
      hops.push(url);
      if (url === "https://a.example/x") {
        return { status: 302, headers: new Map([["location", "https://b.example/y"]]) };
      }
      return { status: 200, ok: true, headers: new Map() };
    },
    async () => {
      const res = await httpsFetcher("https://a.example/x");
      assert.equal(res.status, 200);
      assert.deepEqual(hops, ["https://a.example/x", "https://b.example/y"]);
    },
  );
  await withFetch(
    async () => ({ status: 302, headers: new Map([["location", "http://evil.example/"]]) }),
    () =>
      assert.rejects(httpsFetcher("https://a.example/x"), /redirected off https/),
  );
});

test("httpsFetcher caps the redirect chain", async () => {
  await withFetch(
    async (url) => ({
      status: 302,
      headers: new Map([["location", url + "0"]]),
    }),
    () => assert.rejects(httpsFetcher("https://a.example/x"), /too many redirects/),
  );
});

test("operator-plus-wildcard requirements are partial versions, as Cargo reads them", () => {
  assert.equal(reqMatches(">=1.*", "1.0.0"), true);
  assert.equal(reqMatches(">=1.*", "0.9.0"), false);
  assert.equal(reqMatches("^1.2.*", "1.9.0"), true);
  assert.equal(reqMatches("<=1.2.*", "1.2.9"), true);
  assert.equal(reqMatches("<=1.2.*", "1.3.0"), false);
  assert.equal(reqMatches(">=*", "1.0.0"), null);
  assert.equal(reqMatches("1.*.2", "1.0.2"), null);
});
