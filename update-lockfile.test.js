const withFetch = async (impl, run) => {
  const real = globalThis.fetch;
  globalThis.fetch = impl;
  try {
    return await run();
  } finally {
    globalThis.fetch = real;
  }
};

test("httpsFetcher follows https redirects and refuses an http hop", async () => {
  const hops = [];
  await withFetch(
    async (url) => {
      hops.push(url);
      if (url === "https://a.example/x") {
        return { status: 302, headers: new Map([["location", "https://b.example/y"]]) };
      }
      return { status: 200, ok: true, headers: new Map() };
    },
    async () => {
      const res = await httpsFetcher("https://a.example/x");
      assert.equal(res.status, 200);
      assert.deepEqual(hops, ["https://a.example/x", "https://b.example/y"]);
    },
  );
  await withFetch(
    async () => ({ status: 302, headers: new Map([["location", "http://evil.example/"]]) }),
    () =>
      assert.rejects(httpsFetcher("https://a.example/x"), /redirected off https/),
  );
});

