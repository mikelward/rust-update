test("semver parsing, ordering, and stability", () => {
  assert.deepEqual(parseSemver("1.2.3"), { major: 1, minor: 2, patch: 3, prerelease: null });
  assert.equal(parseSemver("1.2"), null);
  assert.equal(parseSemver("01.2.3"), null);
  assert.ok(compareSemver("1.2.10", "1.2.9") > 0);
  assert.ok(compareSemver("1.0.0-alpha", "1.0.0") < 0);
  assert.ok(compareSemver("1.0.0-alpha.1", "1.0.0-alpha") > 0);
  assert.ok(compareSemver("1.0.0-2", "1.0.0-11") < 0); // numeric identifiers compare numerically
  assert.ok(compareSemver("1.0.0-alpha", "1.0.0-1") > 0); // numeric below alphanumeric
  assert.equal(compareSemver("1.0.0+a", "1.0.0+b"), 0); // build metadata ignored
  assert.ok(isStable("1.2.3"));
  assert.ok(isStable("1.2.3+meta"));
  assert.ok(!isStable("1.2.3-rc.1"));
  assert.ok(!isStable("not-a-version"));
});

test("reqMatches transcribes the semver crate's comparator semantics", () => {
  const table = [
    // caret, bare-as-caret, and the 0.x ladder
    ["^1.2.3", "1.2.4", true], ["^1.2.3", "1.3.0", true], ["^1.2.3", "2.0.0", false],
    ["^1.2.3", "1.2.2", false], ["1.2.3", "1.2.4", true],
    ["^0.2.3", "0.2.9", true], ["^0.2.3", "0.3.0", false],
    ["^0.0.3", "0.0.3", true], ["^0.0.3", "0.0.4", false],
    ["^0", "0.9.9", true], ["^0", "1.0.0", false],
    ["^0.0", "0.0.9", true], ["^0.0", "0.1.0", false],
    // tilde
    ["~1.2.3", "1.2.9", true], ["~1.2.3", "1.3.0", false],
    ["~1.2", "1.2.0", true], ["~1.2", "1.3.0", false],
    ["~1", "1.9.0", true], ["~1", "2.0.0", false],
    // exact, full and partial
    ["=1.2.3", "1.2.3", true], ["=1.2.3", "1.2.4", false],
    ["=1.2", "1.2.9", true], ["=1.2", "1.3.0", false],
    // ordered comparators, partials per the crate's equivalences
    [">=1.2, <1.5", "1.4.0", true], [">=1.2, <1.5", "1.5.0", false],
    [">1.2", "1.3.0", true], [">1.2", "1.2.9", false],
    ["<=1.2", "1.2.9", true], ["<=1.2", "1.3.0", false],
    ["<1", "0.9.0", true], ["<1", "1.0.0", false],
    // wildcards
    ["*", "1.0.0", true], ["1.*", "1.5.0", true], ["1.*", "2.0.0", false],
    // the prerelease gate: same triple plus a prerelease on the comparator
    ["*", "1.0.0-rc.1", false], [">=1.0.0", "1.0.1-rc.1", false],
    ["=2.0.0-rc.1", "2.0.0-rc.1", true], [">=1.0.0-alpha", "1.0.0-beta", true],
    // admission is per REQUIREMENT: one same-triple prerelease comparator
    // admits the version for every other comparator's ordinary ordering
    [">=1.0.0-alpha, <2.0.0", "1.0.0-beta", true], ["<2.0.0", "1.0.0-beta", false],
    // refusals, never passes
    ["bogus", "1.0.0", null], [">=*", "1.0.0", null], ["~1.2-beta", "1.2.0", null],
    ["", "1.0.0", null], ["^1.0.0", "not-a-version", null],
  ];
  for (const [req, version, expected] of table) {
    assert.equal(reqMatches(req, version), expected, `${JSON.stringify(req)} vs ${version}`);
  }
});

