test("parseLockfile reads packages, workspace members, and raw extra sections", () => {
  const text = renderLock(
    [
      reg({ name: "libc", version: "0.2.186", deps: [] }),
      { name: "app", version: "0.0.0", deps: ["libc", "syn 2.0.119"] },
    ],
    { extra: '\n[[patch.unused]]\nname = "quux"\nversion = "1.0.0"\n' },
  );
  const lock = parseLockfile(text);
  assert.deepEqual(lock.errors, []);
  assert.equal(lock.version, 4);
  assert.equal(lock.packages.length, 2);
  assert.equal(lock.packages[0].source, CRATES_IO_SOURCE);
  assert.equal(lock.packages[0].checksum, "c-libc-0.2.186");
  assert.equal(lock.packages[1].source, null);
  assert.deepEqual(lock.packages[1].dependencies, ["libc", "syn 2.0.119"]);
  assert.equal(lock.others.length, 1);
  assert.match(lock.others[0].header, /patch\.unused/);
  assert.match(lock.others[0].raw.join("\n"), /quux/);
  assert.deepEqual(workspaceMembers(lock).map((p) => p.name), ["app"]);
});

test("parseLockfile refuses fields and shapes Cargo does not emit", () => {
  for (const [mutation, message] of [
    ["replace = \"other 1.0.0\"", /unrecognized package field/],
    ["name = \"twice\"", /duplicate name/],
  ]) {
    const text = renderLock([reg({ name: "a", version: "1.0.0" })]).replace(
      'checksum = "c-a-1.0.0"',
      `checksum = "c-a-1.0.0"\n${mutation}`,
    );
    const lock = parseLockfile(text);
    assert.equal(lock.errors.length, 1, mutation);
    assert.match(lock.errors[0], message);
  }
  assert.match(
    parseLockfile('[[package]]\nname = "a"\nversion = "1.0.0"\n').errors.join("\n"),
    /no `version = N` line/,
  );
  assert.match(
    parseLockfile(renderLock([]) + '\n[[package]]\nname = "a"\nversion = "1.0.0"\ndependencies = [\n "b",\n').errors.join("\n"),
    /unterminated dependencies/,
  );
});

