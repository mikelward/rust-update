const walkDeps = (crates) => {
  const { fetcher } = makeFetcher(crates);
  return {
    cooldownDays: 5,
    now: NOW,
    versionDate: (name, version) => fetchVersionDate(name, version, fetcher),
  };
};

test("findPinback takes the newest eligible candidate below the chosen one", async () => {
  const crates = {
    a: {
      versions: [
        { vers: "1.2.0" }, { vers: "1.2.1" }, { vers: "1.2.2", yanked: true },
        { vers: "1.2.3-rc.1" }, { vers: "1.2.4" }, { vers: "1.2.5" }, { vers: "2.0.0" },
      ],
      dates: { "1.2.1": OLD_DATE, "1.2.4": OLD_DATE, "1.2.5": FRESH_DATE },
    },
  };
  const { candidate, reasons } = await findPinback(
    "a", "1.2.5", "1.2.0",
    { versions: crates.a.versions },
    walkDeps(crates),
  );
  // 1.2.4 wins: 1.2.5 is the vacated version, 2.0.0 is out of the group,
  // the rc and the yank never qualify — and the reasons say nothing,
  // because nothing eligible was passed over.
  assert.equal(candidate, "1.2.4");
  assert.deepEqual(reasons, []);
});

test("findPinback respects the floor, defers cooling candidates, and caps missing dates", async () => {
  const crates = {
    a: {
      versions: [{ vers: "1.2.1" }, { vers: "1.2.2" }, { vers: "1.2.3" }, { vers: "1.2.4" }],
      dates: { "1.2.4": FRESH_DATE, "1.2.1": OLD_DATE },
    },
  };
  // Floor 1.2.2: only 1.2.4 (cooling) and 1.2.3 (dateless) sit strictly
  // between the floor and the vacated 1.2.5, so nothing qualifies — the
  // floor itself is excluded because the caller's own fallback covers it.
  const walk = walkDeps(crates);
  const held = await findPinback("a", "1.2.5", "1.2.2", { versions: crates.a.versions }, walk);
  assert.equal(held.candidate, null);
  assert.equal(held.reasons.length, 2);
  assert.match(held.reasons[0], /inside the 5-day cooldown/);
  assert.match(held.reasons[1], /no publish date/);
  // Floor lifted: the walk continues past the dateless pair to 1.2.1.
  const found = await findPinback("a", "1.2.5", null, { versions: crates.a.versions }, walk);
  assert.equal(found.candidate, "1.2.1");
});

