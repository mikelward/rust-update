const renderLock = (packages, { version = 4, extra = "" } = {}) => {
  let out =
    "# This file is automatically @generated by Cargo.\n" +
    "# It is not intended for manual editing.\n" +
    `version = ${version}\n`;
  for (const p of packages) {
    out += `\n[[package]]\nname = "${p.name}"\nversion = "${p.version}"\n`;
    if (p.source !== undefined && p.source !== null) out += `source = "${p.source}"\n`;
    if (p.checksum !== undefined) out += `checksum = "${p.checksum}"\n`;
    else if (p.source !== undefined && p.source !== null) out += `checksum = "c-${p.name}-${p.version}"\n`;
    if (p.deps !== undefined && p.deps.length > 0) {
      out += "dependencies = [\n";
      for (const d of p.deps) out += ` "${d}",\n`;
      out += "]\n";
    }
  }
  return out + extra;
};

const reg = (p) => ({ source: CRATES_IO_SOURCE, ...p });

// crates: { name: { versions: [{vers, yanked?, cksum?, deps?}], dates: { vers: iso } } }
const makeFetcher = (crates) => {
  const requests = [];
  const fetcher = async (url) => {
    requests.push(url);
    if (url.startsWith(INDEX_URL + "/")) {
      const name = url.slice(url.lastIndexOf("/") + 1);
      const crate = crates[name];
      if (!crate) return { ok: false, status: 404, text: async () => "" };
      const body = crate.versions
        .map((v) =>
          JSON.stringify({
            name,
            vers: v.vers,
            cksum: v.cksum ?? `c-${name}-${v.vers}`,
            yanked: v.yanked ?? false,
            deps: v.deps ?? [],
          }),
        )
        .join("\n");
      return { ok: true, status: 200, text: async () => body };
    }
    const api = new RegExp(`^${API_URL}/crates/([^/]+)/([^/]+)$`).exec(url);
    if (api) {
      const crate = crates[decodeURIComponent(api[1])];
      const date = crate?.dates?.[decodeURIComponent(api[2])];
      if (!date) return { ok: false, status: 404, json: async () => ({}) };
      return { ok: true, status: 200, json: async () => ({ version: { created_at: date } }) };
    }
    throw new Error(`unexpected URL: ${url}`);
  };
  return { fetcher, requests };
};

// A cargo whose `update` swaps in a prepared resolution and whose
// `--precise` rewrites one package's version in place (checksum too, as the
// real one does). `refuse` lets a test model the resolver rejecting a pin;
// `onPrecise` lets one model a pin that reshapes the graph.
const makeCargo = (state, { updated, refuse, onPrecise } = {}) => {
  const calls = [];
  const runCargo = (args) => {
    calls.push(args.join(" "));
    if (args.length === 1 && args[0] === "update") {
      state.text = updated;
      return { ok: true, output: "" };
    }
    if (args[0] === "update" && args[2] === "--precise") {
      const spec = args[1];
      const bare = spec.includes("#") ? spec.slice(spec.indexOf("#") + 1) : spec;
      const [name, at] = bare.split("@");
      const to = args[3];
      if (refuse && refuse(name, at, to)) {
        return { ok: false, output: `error: failed to select a version for ${name}` };
      }
      if (onPrecise) {
        state.text = onPrecise(name, at, to, state.text);
        return { ok: true, output: "" };
      }
      const lock = parseLockfile(state.text);
      const pkg = lock.packages.find((p) => p.name === name && p.version === at);
      if (!pkg) return { ok: false, output: `error: package ID specification ${args[1]} did not match` };
      state.text = state.text
        .replace(`name = "${name}"\nversion = "${at}"`, `name = "${name}"\nversion = "${to}"`)
        .replace(`checksum = "c-${name}-${at}"`, `checksum = "c-${name}-${to}"`);
      return { ok: true, output: "" };
    }
    throw new Error(`unexpected cargo invocation: ${args.join(" ")}`);
  };
  return { runCargo, calls };
};

const NOW = new Date("2026-08-18T12:00:00Z");
const OLD_DATE = "2026-08-01T00:00:00Z"; // outside a 5-day cooldown
const FRESH_DATE = "2026-08-17T00:00:00Z"; // inside it

const runUpdate = (state, cargoOpts, crates, opts = {}) => {
  const cargo = makeCargo(state, cargoOpts);
  const net = makeFetcher(crates);
  const result = updateLockfile({
    readLockfile: () => state.text,
    runCargo: cargo.runCargo,
    fetcher: net.fetcher,
    now: NOW,
    cooldownDays: 5,
    ...opts,
  });
  return { result, cargo, net };
};

